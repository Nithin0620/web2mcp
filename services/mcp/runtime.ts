import { db } from '../../lib/db/client';
import { tools } from '../../lib/db/schema';
import { eq } from 'drizzle-orm';
import type { GeneratedTool, ToolParametersSchema } from '../../types/platform';
import { requestApprovalToken, verifyApprovalToken } from './safety-gate';
import { executeProbe } from '../validation/probe-runner';
import { recordEvidence } from '../validation/evidence-vault';

export interface JSONRPCRequest {
  jsonrpc: '2.0';
  id?: string | number | null;
  method: string;
  params?: Record<string, any>;
}

export interface JSONRPCResponse {
  jsonrpc: '2.0';
  id?: string | number | null;
  result?: any;
  error?: {
    code: number;
    message: string;
    data?: any;
  };
}

export async function handleMCPRequest(
  projectId: string,
  request: JSONRPCRequest
): Promise<JSONRPCResponse> {
  const { id = null, method, params = {} } = request;

  try {
    switch (method) {
      case 'initialize': {
        return {
          jsonrpc: '2.0',
          id,
          result: {
            protocolVersion: '2024-11-05',
            capabilities: {
              tools: {},
            },
            serverInfo: {
              name: 'Web2MCP-Server',
              version: '1.0.0',
            },
          },
        };
      }

      case 'notifications/initialized': {
        return {
          jsonrpc: '2.0',
          id,
          result: {},
        };
      }

      case 'ping': {
        return {
          jsonrpc: '2.0',
          id,
          result: {},
        };
      }

      case 'tools/list': {
        const rows = await db.select().from(tools).where(eq(tools.projectId, projectId));
        const mcpTools = rows.map(r => {
          const schema = JSON.parse(r.parameters) as ToolParametersSchema;

          if (r.requiresApproval) {
            schema.properties = {
              ...schema.properties,
              approvalToken: {
                type: 'string',
                description: 'Required authorization token generated by Web2MCP Safety Gate before executing this consequential action.',
              },
            };
          }

          return {
            name: r.name,
            description: r.description,
            inputSchema: schema,
          };
        });

        return {
          jsonrpc: '2.0',
          id,
          result: {
            tools: mcpTools,
          },
        };
      }

      case 'tools/call': {
        const { name, arguments: args = {} } = params;
        if (!name) {
          return {
            jsonrpc: '2.0',
            id,
            error: { code: -32602, message: 'Missing tool name in tools/call parameters' },
          };
        }

        const allTools = await db.select().from(tools).where(eq(tools.projectId, projectId));
        const matched = allTools.find(t => t.name === name);

        if (!matched) {
          return {
            jsonrpc: '2.0',
            id,
            error: { code: -32601, message: `Tool '${name}' not found for project ${projectId}` },
          };
        }

        const generatedTool: GeneratedTool = {
          id: matched.id,
          projectId: matched.projectId,
          name: matched.name,
          description: matched.description,
          category: matched.category as any,
          parameters: JSON.parse(matched.parameters),
          handlerType: matched.handlerType as any,
          handlerConfig: JSON.parse(matched.handlerConfig),
          requiresApproval: Boolean(matched.requiresApproval),
          riskLevel: matched.riskLevel as any,
          status: matched.status as any,
          createdAt: matched.createdAt,
          updatedAt: matched.updatedAt,
        };

        // Safety Gate Check
        if (generatedTool.requiresApproval) {
          const providedToken = args.approvalToken as string | undefined;
          const isAuthorized = verifyApprovalToken(providedToken, generatedTool.name);

          if (!isAuthorized) {
            const { token, message } = requestApprovalToken(generatedTool.name, projectId);
            return {
              jsonrpc: '2.0',
              id,
              result: {
                content: [
                  {
                    type: 'text',
                    text: message,
                  },
                ],
                isError: true,
                requiresApproval: true,
                approvalToken: token,
              },
            };
          }
        }

        // Execute tool action / probe
        const probeResult = await executeProbe(generatedTool, args);

        // Record execution into Evidence Vault
        await recordEvidence({
          projectId,
          toolId: generatedTool.id,
          toolName: generatedTool.name,
          probeInput: args,
          sampleOutput: probeResult.output,
          domHash: probeResult.domHash,
          status: probeResult.status,
          latencyMs: probeResult.latencyMs,
          errorMessage: probeResult.errorMessage,
        });

        const isFailed = probeResult.status === 'failed';
        const formattedContent =
          probeResult.output !== null && probeResult.output !== undefined
            ? typeof probeResult.output === 'string'
              ? probeResult.output
              : JSON.stringify(probeResult.output, null, 2)
            : probeResult.errorMessage
            ? `Tool execution failed: ${probeResult.errorMessage}`
            : `Tool '${generatedTool.name}' produced no output.`;

        return {
          jsonrpc: '2.0',
          id,
          result: {
            content: [
              {
                type: 'text',
                text: formattedContent,
              },
            ],
            isError: isFailed,
          },
        };
      }

      default:
        return {
          jsonrpc: '2.0',
          id,
          error: { code: -32601, message: `Unsupported method: ${method}` },
        };
    }
  } catch (err: unknown) {
    const errorMsg = err instanceof Error ? err.message : String(err);
    return {
      jsonrpc: '2.0',
      id,
      error: { code: -32603, message: `Internal server error: ${errorMsg}` },
    };
  }
}
